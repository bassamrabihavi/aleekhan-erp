#!/usr/bin/env python3
"""Runtime dependency lock (PHASE_00 / 00.7): ``backend/requirements.lock``.

``backend/requirements.txt`` pins the *direct* runtime dependencies. This tool walks their dependency graph
in the CURRENT virtualenv (``importlib.metadata``; no network, no pip-tools) and writes every runtime
package - direct and transitive - with its exact installed version. Platform-conditional dependencies keep
their environment marker (e.g. ``tzdata ... ; sys_platform == "win32"``), so the lock generated on Windows is
also valid on Linux. Dev/QA tools (requirements-dev.txt) are NOT in the lock.

    python tools/lock_runtime.py            # write backend/requirements.lock
    python tools/lock_runtime.py --check    # exit 1 if the lock differs from the venv (CI)

The lock feeds the dependency scan (``pip-audit -r backend/requirements.lock --no-deps --disable-pip``) and
can be used for reproducible installs: ``pip install -r backend/requirements.lock``.
"""

from __future__ import annotations

import argparse
import re
import sys
from importlib import metadata
from pathlib import Path

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
REQS = ROOT / "backend" / "requirements.txt"
LOCK = ROOT / "backend" / "requirements.lock"
HEADER = (
    "# GENERATED by tools/lock_runtime.py from backend/requirements.txt - do not edit by hand.\n"
    "# Runtime dependencies (direct + transitive), exact versions installed in the venv; markers kept.\n"
)


def _direct() -> list[Requirement]:
    out = []
    for raw in REQS.read_text(encoding="utf-8").splitlines():
        line = raw.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            out.append(Requirement(line))
    return out


def _marker_for_extra(marker: Marker | None, extras: set[str]) -> tuple[bool, str | None]:
    """(applies with the requested extras on *some* platform, platform marker text to keep)."""
    if marker is None:
        return True, None
    text = str(marker)
    if "extra" in text:
        if not any(marker.evaluate({"extra": e}) for e in extras or {""}):
            return False, None
        return True, None  # extras-only markers are resolved here
    return True, text


def resolve() -> dict[str, tuple[str, str, str | None]]:
    """canonical name -> (project name, version, marker or None)."""
    found: dict[str, tuple[str, str, str | None]] = {}
    queue: list[tuple[Requirement, str | None]] = [
        (r, str(r.marker) if r.marker else None) for r in _direct()
    ]
    while queue:
        req, inherited = queue.pop(0)
        key = canonicalize_name(req.name)
        try:
            dist = metadata.distribution(req.name)
        except metadata.PackageNotFoundError:
            if inherited and not Marker(inherited).evaluate():
                continue  # dependency for another platform, not installed here
            raise SystemExit(f"lock_runtime: {req.name} is required but not installed in this venv") from None
        name, version = dist.metadata["Name"], dist.version
        prev = found.get(key)
        marker = inherited if prev is None else (None if prev[2] is None or inherited is None else prev[2])
        found[key] = (name, version, marker)
        if prev is not None:
            continue
        for raw in dist.requires or []:
            dep = Requirement(raw)
            applies, mtext = _marker_for_extra(dep.marker, set(req.extras))
            if not applies:
                continue
            if mtext and not Marker(mtext).evaluate() and not _installed(dep.name):
                continue
            queue.append((dep, mtext or inherited))
    return found


def _installed(name: str) -> bool:
    try:
        metadata.distribution(name)
        return True
    except metadata.PackageNotFoundError:
        return False


def render(found: dict[str, tuple[str, str, str | None]]) -> str:
    lines = [HEADER]
    for _key, (name, version, marker) in sorted(found.items()):
        lines.append(f"{name}=={version}" + (f" ; {marker}" if marker else "") + "\n")
    return "".join(lines)


def _entries(text: str) -> dict[str, str]:
    out = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        req_part, _, marker = line.partition(";")
        if marker.strip() and not Marker(marker.strip()).evaluate():
            continue  # other platform: not comparable here
        m = re.fullmatch(r"([A-Za-z0-9_.-]+)==(\S+)", req_part.strip())
        if m:
            out[canonicalize_name(m.group(1))] = m.group(2)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render(resolve())
    if args.check:
        want, have = _entries(LOCK.read_text(encoding="utf-8")), _entries(text)
        if want != have:
            diff = sorted(set(want.items()) ^ set(have.items()))
            print(f"lock_runtime: requirements.lock differs from the venv: {diff}")
            return 1
        print(f"lock_runtime: requirements.lock matches the venv ({len(have)} packages for this platform)")
        return 0
    LOCK.write_text(text, encoding="utf-8", newline="\n")
    print(f"lock_runtime: wrote {LOCK.relative_to(ROOT)} ({text.count(chr(10)) - 2} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
